import os
import subprocess
import shutil
import uuid
import docx
from fastapi import FastAPI, UploadFile, File, HTTPException, BackgroundTasks
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse
from pdf2docx import Converter

app = FastAPI(title="Resumora Engine")

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

TEMP_DIR = "/tmp/conversions"
os.makedirs(TEMP_DIR, exist_ok=True)

def cleanup_files(*file_paths):
    """Temporary files ko background me safely delete karne ke liye"""
    for path in file_paths:
        if path and os.path.exists(path):
            try:
                os.remove(path)
            except Exception:
                pass

def clean_and_brand_docx(docx_path: str):
    """Python-docx metadata ko override karke Resumora branding set karta hai"""
    try:
        doc = docx.Document(docx_path)
        core_props = doc.core_properties
        core_props.author = "Resumora Universe"
        core_props.last_modified_by = "Resumora Universe"
        core_props.comments = "Processed via Resumora Engine"
        doc.save(docx_path)
    except Exception as err:
        print(f"Metadata sanitize error: {err}")

@app.get("/")
def home():
    return {"status": "online", "message": "Resumora Engine Active"}

# 1. WORD TO PDF (LibreOffice Headless)
@app.post("/convert/word-to-pdf")
async def word_to_pdf(background_tasks: BackgroundTasks, file: UploadFile = File(...)):
    if not (file.filename.endswith(".docx") or file.filename.endswith(".doc")):
        raise HTTPException(status_code=400, detail="Only DOC or DOCX allowed")

    session_id = str(uuid.uuid4())
    input_file = os.path.join(TEMP_DIR, f"{session_id}_{file.filename}")

    with open(input_file, "wb") as buffer:
        shutil.copyfileobj(file.file, buffer)

    try:
        cmd = [
            "libreoffice",
            "--headless",
            "--convert-to", "pdf",
            input_file,
            "--outdir", TEMP_DIR
        ]
        subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)

        base_name = os.path.splitext(input_file)[0]
        output_pdf = f"{base_name}.pdf"

        if not os.path.exists(output_pdf):
            raise HTTPException(status_code=500, detail="Conversion failed")

        # Response deliver hone ke baad files safely clean ho jayengi
        background_tasks.add_task(cleanup_files, input_file, output_pdf)

        return FileResponse(
            output_pdf,
            media_type="application/pdf",
            filename=f"{os.path.splitext(file.filename)[0]}.pdf"
        )
    except Exception as e:
        cleanup_files(input_file)
        raise HTTPException(status_code=500, detail=f"Word to PDF conversion error: {str(e)}")

# 2. PDF TO WORD (Clean Layout & Resumora Branding)
@app.post("/convert/pdf-to-word")
async def pdf_to_word(background_tasks: BackgroundTasks, file: UploadFile = File(...)):
    if not file.filename.endswith(".pdf"):
        raise HTTPException(status_code=400, detail="Only PDF allowed")

    session_id = str(uuid.uuid4())
    input_file = os.path.join(TEMP_DIR, f"{session_id}_{file.filename}")
    output_docx = os.path.join(TEMP_DIR, f"{session_id}_converted.docx")

    with open(input_file, "wb") as buffer:
        shutil.copyfileobj(file.file, buffer)

    try:
        # Optimized parser taaki line merge aur formatting issue na aaye
        cv = Converter(input_file)
        cv.convert(
            output_docx,
            start=0,
            end=None,
            multi_processing=False,
            keep_layout=True
        )
        cv.close()

        if not os.path.exists(output_docx) or os.path.getsize(output_docx) < 500:
            raise HTTPException(status_code=500, detail="Conversion output empty")

        # "Generated by python-docx" metadata hatana
        clean_and_brand_docx(output_docx)

        background_tasks.add_task(cleanup_files, input_file, output_docx)

        return FileResponse(
            output_docx,
            media_type="application/vnd.openxmlformats-officedocument.wordprocessingml.document",
            filename=f"{os.path.splitext(file.filename)[0]}.docx"
        )
    except Exception as e:
        print(f"pdf2docx primary failed: {e}")
        # Secondary fallback (LibreOffice)
        try:
            cmd = [
                "libreoffice",
                "--headless",
                "--convert-to", "docx",
                input_file,
                "--outdir", TEMP_DIR
            ]
            subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=40)
            base_name = os.path.splitext(input_file)[0]
            lo_output = f"{base_name}.docx"
            if os.path.exists(lo_output) and os.path.getsize(lo_output) > 500:
                clean_and_brand_docx(lo_output)
                background_tasks.add_task(cleanup_files, input_file, lo_output)
                return FileResponse(
                    lo_output,
                    media_type="application/vnd.openxmlformats-officedocument.wordprocessingml.document",
                    filename=f"{os.path.splitext(file.filename)[0]}.docx"
                )
        except Exception as lo_err:
            print(f"Fallback error: {lo_err}")

        cleanup_files(input_file, output_docx)
        raise HTTPException(status_code=500, detail="Could not parse document structure.")
